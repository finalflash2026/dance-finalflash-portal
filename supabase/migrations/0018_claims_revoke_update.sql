-- =========================================================
-- 0018_claims_revoke_update.sql
-- 脆弱性対策 M-1: claims テーブルの UPDATE 権限を明示的に除外する。
--
-- claims には UPDATE ポリシーが無いため RLS が暗黙的に拒否しているが、
-- 将来のポリシー追加時の事故を防ぐために GRANT レベルでも除外する。
--
-- 0001〜0017 適用済みの環境に対して追加で流す。
-- =========================================================

-- claims は追加と削除だけ。書き換えは許さない (SPEC §6.1)
revoke update on public.claims from authenticated;
