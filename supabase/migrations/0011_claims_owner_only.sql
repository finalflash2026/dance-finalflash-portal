-- これまで折衝・管理者も他人の申請を消せた。実際に**他の人の申請を
-- 取り消せてしまう**と報告があり、画面にも取消ボタンが出ていた。
--
-- 折衝が申請を消したい場面は「コマごと消す・作り直す」ときだが、
-- そちらは `claims.slot_id` の on delete cascade が面倒を見る。
-- **申請そのものを直接消す必要がない**ので、権限ごと外す。
--
-- 申請は「その人がその時間に練習する」という本人の意思表示で、
-- 取り消してよいのは本人だけ。誰かの都合で消えると、本人は
-- 消えたことにすら気づけない。
drop policy if exists del_claims on public.claims;

create policy del_claims on public.claims for delete to authenticated
  using (user_id = auth.uid());
