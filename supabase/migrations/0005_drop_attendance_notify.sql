-- ---------- 出欠変更のお知らせをやめる (SPEC §6.4.2 / v1.11) ----------
-- 公式練は「そのジャンルを1〜3ジャンに持ち対象期に該当する全メンバー」が
-- 参加者なので、1人が遅刻を登録するだけで数十行のお知らせが生まれていた。
-- 出欠の状況は出欠管理窓を開けば分かるため、通知の量に見合う価値が無い。
--
-- **トリガだけでなく関数も消す。** 残しておくと「まだ通知しているのでは」と
-- 読み手を迷わせるうえ、うっかりトリガを付け直せてしまう。
drop trigger if exists trg_notify_attendance on public.attendances;
drop function if exists public.notify_attendance();

-- 既に配ってしまった出欠のお知らせを片付ける。
-- 未読のまま残ると「もう出さない」と決めた通知が画面に出続けるため。
delete from public.notifications where type = 'attendance_updated';

-- 注: notifications.type の CHECK 制約から 'attendance_updated' は外さない。
-- 既存の制約を張り替えるだけの利点が無く、値が使われなくなるだけで済むため。
