-- ナンバー練には 23:00〜翌06:00 のような夜通しの練習がある。
-- これまで `start_time < end_time` を要求していたため登録できなかった。
--
-- **終了が開始以前なら「翌日まで」と読む**ことにする。営業時間の書き方と
-- 同じ約束で、列を増やさずに済む。日付をまたぐかどうかは 1か所
-- (lib/day-span.ts) に閉じ込め、画面と ics はそこを通す。
--
-- 別案として `end_date` 列を持たせる案もあったが、
--   - 同じ情報が2か所に載り、ずれる余地ができる (3日後などを入れられる)
--   - 既存の全行に既定値を入れる必要がある
-- ため採らなかった。
alter table public.number_events
  drop constraint if exists number_events_check;

-- **同じ時刻は禁止したまま。** 0分の予定なのか24時間の予定なのか
-- 決めようがなく、どちらに読んでも利用者の意図とずれる。
alter table public.number_events
  add constraint number_events_times_differ
  check (start_time <> end_time);
